import pandas as pd
import numpy as np
import urllib.request
import zipfile
import io

# Direct path to the actual zip package
url = "https://archive.ics.uci.edu/ml/machine-learning-databases/00360/AirQualityUCI.zip"
print("Downloading the dataset... Please wait.")

req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
with urllib.request.urlopen(req) as response:
    zip_bytes = response.read()

with zipfile.ZipFile(io.BytesIO(zip_bytes)) as z:
    df = pd.read_csv(z.open('AirQualityUCI.csv'), sep=';', decimal=',')

print("Data loaded successfully!")
print(f"Initial Shape: {df.shape[0]} rows and {df.shape[1]} columns.")

# 1. Look at the raw structure of the first few rows
print("--- Raw Data Sample ---")
print(df.head(2))

# 2. Drop completely blank rows and columns that are common in this CSV format
df = df.dropna(how='all')
# Remove any unnamed columns if they exist
df = df.loc[:, ~df.columns.str.contains('^Unnamed')]

# 3. Clean Date and Time columns and merge them into a unified index
# The dataset has dates as DD/MM/YYYY and times as HH.MM.SS
df['Datetime'] = pd.to_datetime(df['Date'] + ' ' + df['Time'], format='%d/%m/%Y %H.%M.%S', errors='coerce')

# Drop rows where Datetime conversion failed, then sort chronologically
df = df.dropna(subset=['Datetime']).set_index('Datetime').sort_index()

# Drop the old separate Date and Time columns since we don't need them anymore
df = df.drop(columns=['Date', 'Time'])

# 4. Handle invalid missing values: The dataset replaces missing data with -200
print("\nCounting missing sensor flags (-200 values):")
print((df == -200).sum())

# Replace -200 with proper mathematical NaN (Not a Number) values
df = df.replace(-200, np.nan)

# Fill missing spaces using Forward Fill (propagates the last valid reading forward in time)
df = df.ffill().bfill()

print("\n--- Cleaned Dataset Summary ---")
print(f"Final shape: {df.shape[0]} rows, {df.shape[1]} columns")
print("Missing values remaining:", df.isna().sum().sum())

import matplotlib.pyplot as plt
import seaborn as sns

# Set style for high-quality charts
sns.set_theme(style="whitegrid")
fig, axes = plt.subplots(3, 1, figsize=(12, 16))

# Chart 1: Distribution of Benzene
sns.histplot(df['C6H6(GT)'], kde=True, ax=axes[0], color='teal')
axes[0].set_title('Distribution of Benzene (C6H6) Concentrations')
axes[0].set_xlabel('Concentration')

# Chart 2: Time-based Trend (Hourly Profile)
# This identifies daily traffic rush-hour patterns
hourly_avg = df.groupby(df.index.hour)['C6H6(GT)'].mean()
sns.barplot(x=hourly_avg.index, y=hourly_avg.values, ax=axes[1], color='royalblue')
axes[1].set_title('Diurnal Patterns: Average Benzene Concentration by Hour of Day')
axes[1].set_xlabel('Hour of the Day')
axes[1].set_ylabel('Avg Concentration')

# Chart 3: Correlation Matrix Heatmap
# Shows relationships between variables
corr = df.corr()
sns.heatmap(corr, annot=False, cmap='coolwarm', ax=axes[2])
axes[2].set_title('Correlation Heatmap Matrix of Pollutants & Weather')

plt.tight_layout()
plt.show()

from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
import numpy as np

# ==========================================
# PART C: FEATURE ENGINEERING
# ==========================================
# Create time-based features from the index
df['Hour'] = df.index.hour
df['DayOfWeek'] = df.index.dayofweek

# Create historical lag features (past observations)
df['Lag_1h'] = df['C6H6(GT)'].shift(1)
df['Lag_2h'] = df['C6H6(GT)'].shift(2)

# Create a rolling window feature (average of the last 3 hours)
df['Rolling_Mean_3h'] = df['C6H6(GT)'].shift(1).rolling(window=3).mean()

# Drop the first few rows because they won't have past lags calculated
model_data = df.dropna()

# ==========================================
# PART D: CHRONOLOGICAL PREDICTION MODEL
# ==========================================
# Define features (X) and the target variable we want to predict (y)
features = ['Hour', 'DayOfWeek', 'Lag_1h', 'Lag_2h', 'Rolling_Mean_3h']
X = model_data[features]
y = model_data['C6H6(GT)']

# 80/20 Chronological Split (No random splitting to avoid data leakage!)
split_idx = int(len(model_data) * 0.8)
X_train, X_test = X.iloc[:split_idx], X.iloc[split_idx:]
y_train, y_test = y.iloc[:split_idx], y.iloc[split_idx:]

print(f"Training set size: {X_train.shape} rows")
print(f"Testing set size: {X_test.shape} rows\n")

# Initialize and train the Random Forest Model
print("Training the Random Forest Regressor model...")
model = RandomForestRegressor(n_estimators=100, random_state=42)
model.fit(X_train, y_train)

# Make predictions on our test set
predictions = model.predict(X_test)

# Calculate Evaluation Regression Metrics
mae = mean_absolute_error(y_test, predictions)
mse = mean_squared_error(y_test, predictions)
rmse = np.sqrt(mse)
r2 = r2_score(y_test, predictions)

print("\n=== MODEL PERFORMANCE METRICS ===")
print(f"Mean Absolute Error (MAE):     {mae:.4f}")
print(f"Mean Squared Error (MSE):      {mse:.4f}")
print(f"Root Mean Squared Error (RMSE): {rmse:.4f}")
print(f"R2 Score (Variance Explained):  {r2:.4f}")

# ==========================================
# PART E: FEATURE IMPORTANCE ANALYSIS
# ==========================================
# Check which features influenced our predictions the most
importance = model.feature_importances_
print("\n=== FEATURE IMPORTANCE ANALYSIS ===")
for name, val in zip(features, importance):
    print(f"{name:<16}: {val*100:.2f}%")

